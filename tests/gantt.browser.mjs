import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'

const browser = await chromium.launch({ channel: process.env.TEST_BROWSER_CHANNEL || 'msedge' })
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, timezoneId: 'Asia/Tokyo' })
  const page = await context.newPage()
  page.setDefaultTimeout(5000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const url = process.env.TEST_APP_URL || 'http://localhost:5173/'
  const response = await page.goto(url)
  assert.equal(response?.status(), 200)

  const sidebar = page.getByRole('navigation')
  const drawer = page.getByRole('complementary', { name: 'タスク詳細' })
  const draft = page.getByRole('complementary', { name: 'タスクを追加' })
  async function createProject(name) {
    await sidebar.getByRole('button', { name: 'プロジェクトを作成' }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('プロジェクト名').fill(name)
    await dialog.getByRole('button', { name: '作成', exact: true }).click()
    await page.getByRole('heading', { name, exact: true }).waitFor()
  }

  function shift(key, days) {
    const date = new Date(`${key}T00:00:00Z`)
    date.setUTCDate(date.getUTCDate() + days)
    return date.toISOString().slice(0, 10)
  }

  await createProject('引越し準備')
  const chart = page.locator('.vis-panel.vis-center')
  const rect = await chart.boundingBox()
  assert.ok(rect)
  await chart.dblclick({ position: { x: Math.round(rect.width * 4.5 / 14), y: 105 } })
  const chosen = await draft.getByLabel('開始日').inputValue()
  const today = await page.evaluate(() => new Intl.DateTimeFormat('sv-SE', { timeZone: 'Asia/Tokyo' }).format(new Date()))
  assert.equal(chosen, shift(today, 1))
  assert.equal(await draft.getByLabel('終了日').inputValue(), chosen)
  await draft.getByLabel('表題').fill('引越し')
  await draft.getByRole('button', { name: 'タスクを作成' }).click()

  await drawer.getByRole('button', { name: '子タスク' }).click()
  assert.equal(await draft.getByLabel('親タスク').locator('option:checked').textContent(), '引越し')
  await draft.getByLabel('表題').fill('荷物を梱包')
  await draft.getByLabel('終了日').fill(shift(chosen, 3))
  await draft.getByLabel('進捗率（%）').fill('40')
  await draft.getByRole('button', { name: 'タスクを作成' }).click()
  await drawer.getByLabel('表題').waitFor()
  assert.equal(await drawer.getByLabel('表題').inputValue(), '荷物を梱包')
  await drawer.getByLabel('ステータス').selectOption('doing')
  await drawer.getByRole('button', { name: '変更を保存' }).click()
  await page.locator('.vis-item.status-doing').filter({ hasText: '荷物を梱包' }).waitFor()

  const parent = page.getByRole('button', { name: '引越し', exact: true })
  await parent.click()
  assert.equal(await drawer.getByLabel('進捗率（%）').inputValue(), '40')
  assert.equal(await drawer.getByLabel('終了日').inputValue(), shift(chosen, 3))
  assert.equal(await drawer.getByLabel('終了日').isDisabled(), true)
  await page.getByRole('button', { name: '引越しを折りたたむ' }).click()
  assert.equal(await page.getByRole('button', { name: '荷物を梱包' }).count(), 0)
  await page.getByRole('button', { name: '引越しを展開' }).click()
  await page.getByRole('button', { name: '荷物を梱包' }).waitFor()

  const childBar = page.locator('.vis-item.task-bar').filter({ hasText: '荷物を梱包' })
  await childBar.click()
  assert.equal(await drawer.getByLabel('表題').inputValue(), '荷物を梱包')
  const barRect = await childBar.boundingBox()
  assert.ok(barRect)
  const dayWidth = barRect.width / 4
  async function drag(target, delta) {
    const box = await target.boundingBox()
    assert.ok(box)
    const x = box.x + box.width / 2
    const y = box.y + box.height / 2
    await page.mouse.move(x, y)
    await page.mouse.down()
    await page.mouse.move(x + delta, y, { steps: 12 })
    await page.mouse.up()
  }
  async function checkDates(start, end) {
    await page.waitForFunction(({ start, end }) => {
      const dates = [...document.querySelectorAll('.task-drawer input[type=date]')]
      return dates[0]?.value === start && dates[1]?.value === end
    }, { start, end })
  }

  await drag(childBar, dayWidth)
  await checkDates(shift(chosen, 1), shift(chosen, 4))
  await drag(childBar.locator('.vis-drag-right'), dayWidth)
  await checkDates(shift(chosen, 1), shift(chosen, 5))
  await drag(childBar.locator('.vis-drag-left'), -dayWidth)
  await checkDates(chosen, shift(chosen, 5))

  const scale = page.getByRole('group', { name: '表示単位' })
  await scale.getByRole('button', { name: '週', exact: true }).click()
  assert.equal(await scale.getByRole('button', { name: '週', exact: true }).getAttribute('aria-pressed'), 'true')
  await page.locator('.vis-time-axis .vis-text.vis-minor').filter({ hasText: /^\d{1,2}\/\d{1,2}$/ }).first().waitFor()
  await scale.getByRole('button', { name: '月', exact: true }).click()
  assert.equal(await scale.getByRole('button', { name: '月', exact: true }).getAttribute('aria-pressed'), 'true')
  await page.locator('.vis-time-axis .vis-text.vis-minor').filter({ hasText: /^\d{1,2}月$/ }).first().waitFor()
  await createProject('家事')
  assert.equal(await page.getByRole('button', { name: '荷物を梱包' }).count(), 0)
  await sidebar.getByRole('button', { name: 'すべてのタスク' }).click()
  await page.getByRole('button', { name: '荷物を梱包' }).waitFor()
  await page.reload()
  await page.getByRole('button', { name: '荷物を梱包' }).click()
  await checkDates(chosen, shift(chosen, 5))
  assert.equal(await drawer.getByLabel('ステータス').inputValue(), 'doing')

  const titleInput = drawer.getByLabel('表題')
  const description = drawer.getByLabel('説明')
  await titleInput.fill('荷物を梱包')
  await description.click()
  assert.equal(await description.evaluate(el => document.activeElement === el), true)
  await chart.click({ position: { x: 45, y: 220 } })
  assert.equal(await description.evaluate(el => document.activeElement === el), false)

  await drawer.getByRole('button', { name: 'Todo', exact: true }).click()
  const todoForm = drawer.getByRole('region', { name: 'Todo リスト' })
  for (const item of ['箱を用意する', '荷物を詰める']) {
    await todoForm.getByRole('textbox', { name: '新しい Todo' }).fill(item)
    await todoForm.getByRole('button', { name: '追加', exact: true }).click()
    await todoForm.getByRole('checkbox', { name: item, exact: true }).waitFor()
  }
  await todoForm.getByRole('checkbox', { name: '箱を用意する' }).click()
  await todoForm.getByText('1/2 件完了 · 50%').waitFor()
  assert.equal(await todoForm.getByRole('checkbox', { name: '箱を用意する' }).isChecked(), true)
  await page.locator('.vis-label .task-percent').filter({ hasText: '50%' }).nth(1).waitFor()
  await drawer.getByRole('button', { name: '基本情報', exact: true }).click()
  assert.equal(await drawer.getByLabel('進捗率（%）').inputValue(), '50')
  assert.equal(await drawer.getByLabel('進捗率（%）').isDisabled(), true)

  await drawer.getByRole('button', { name: '疑問・懸念', exact: true }).click()
  const issues = drawer.getByRole('region', { name: '疑問・懸念' })
  await issues.getByRole('button', { name: '疑問・懸念を追加' }).click()
  await issues.getByLabel('種別').selectOption('concern')
  await issues.getByLabel('表題').fill('箱の数が足りるか')
  await issues.getByRole('textbox', { name: '詳細', exact: true }).fill('必要な数を数える')
  await issues.getByRole('button', { name: '登録', exact: true }).click()
  await issues.getByLabel('解消済みにする').check()
  await issues.getByLabel('解消内容').fill('予備を2箱確保した')
  await issues.getByRole('button', { name: '保存', exact: true }).click()
  const issueRow = issues.getByRole('button', { name: /^箱の数が足りるか 懸念 · 解消済み/ })
  await issueRow.waitFor()
  await issueRow.click()
  assert.equal(await issues.getByLabel('解消内容').count(), 0)
  await issueRow.click()
  assert.equal(await issues.getByLabel('解消内容').inputValue(), '予備を2箱確保した')

  await page.reload()
  await page.getByRole('button', { name: '荷物を梱包' }).click()
  assert.equal(await drawer.getByLabel('進捗率（%）').inputValue(), '50')
  await drawer.getByRole('button', { name: 'Todo', exact: true }).click()
  assert.equal(await todoForm.getByRole('checkbox', { name: '箱を用意する' }).isChecked(), true)
  await todoForm.getByRole('checkbox', { name: '箱を用意する' }).click()
  await todoForm.getByText('0/2 件完了 · 0%').waitFor()
  assert.equal(await todoForm.getByRole('checkbox', { name: '箱を用意する' }).isChecked(), false)
  await todoForm.getByRole('button', { name: 'Todo「箱を用意する」を削除' }).click()
  await todoForm.getByRole('button', { name: 'Todo「荷物を詰める」を削除' }).click()
  await todoForm.getByText('0/0 件完了').waitFor()
  await drawer.getByRole('button', { name: '基本情報', exact: true }).click()
  assert.equal(await drawer.getByLabel('進捗率（%）').inputValue(), '40')
  await drawer.getByRole('button', { name: '疑問・懸念', exact: true }).click()
  await issueRow.click()
  assert.equal(await issues.getByRole('textbox', { name: '詳細', exact: true }).inputValue(), '必要な数を数える')
  assert.equal(await issues.getByLabel('解消内容').inputValue(), '予備を2箱確保した')

  await drawer.getByRole('button', { name: 'Todo', exact: true }).click()
  await todoForm.getByRole('textbox', { name: '新しい Todo' }).fill('サイズを測る')
  await todoForm.getByRole('button', { name: '追加', exact: true }).click()
  await todoForm.getByRole('button', { name: 'Todo「サイズを測る」の疑問・懸念', exact: true }).click()
  await issues.getByText('新規登録先 Todo「サイズを測る」').waitFor()
  assert.equal(await issueRow.count(), 0)
  await issues.getByRole('button', { name: '疑問・懸念を追加' }).click()
  await issues.getByLabel('表題').fill('測る場所が不明')
  await issues.getByRole('button', { name: '登録', exact: true }).click()
  await issues.getByText('未解消 1 件', { exact: true }).waitFor()
  await drawer.getByRole('button', { name: 'Todo リストへ' }).click()
  await todoForm.getByRole('button', { name: 'Todo「サイズを測る」の疑問・懸念（未解消 1 件）' }).waitFor()
  const parentIssueBadge = page.getByRole('button', { name: '引越しの疑問・懸念（未解消 1 件）', exact: true })
  await page.getByRole('button', { name: '引越しを折りたたむ' }).click()
  await parentIssueBadge.click()
  await issues.getByRole('button', { name: /^測る場所が不明.*Todo「サイズを測る」/ }).waitFor()

  await sidebar.getByRole('button', { name: '引越し準備', exact: true }).click()
  const projectButton = page.locator('.header-actions').getByRole('button', { name: /^疑問・懸念/ })
  await projectButton.getByText('未解消 1', { exact: true }).waitFor()
  await projectButton.click()
  const projectIssues = page.getByRole('dialog', { name: '引越し準備' })
  await projectIssues.getByText('新規登録先 プロジェクト「引越し準備」').waitFor()
  await projectIssues.getByRole('button', { name: '疑問・懸念を追加' }).click()
  await projectIssues.getByLabel('表題').fill('引越し日の確定待ち')
  await projectIssues.getByRole('button', { name: '登録', exact: true }).click()
  await projectIssues.getByText('未解消 2 件', { exact: true }).waitFor()
  await projectIssues.getByRole('button', { name: /^引越し日の確定待ち.*プロジェクト直下/ }).waitFor()
  await projectIssues.getByRole('button', { name: /^測る場所が不明.*Todo「サイズを測る」/ }).click()
  await projectIssues.getByLabel('解消済みにする').check()
  await projectIssues.getByLabel('解消内容').fill('玄関の幅を測ると確認した')
  await projectIssues.getByRole('button', { name: '保存', exact: true }).click()
  await projectIssues.getByText('未解消 1 件', { exact: true }).waitFor()
  await projectIssues.locator('.dialog-close').click()
  assert.equal(await parentIssueBadge.count(), 0)
  await projectButton.getByText('未解消 1', { exact: true }).waitFor()

  const displaySettings = page.getByRole('button', { name: '表示設定' })
  const settingsDialog = page.getByRole('dialog', { name: 'ガントの表示設定' })
  const projectsSetting = settingsDialog.getByRole('checkbox', { name: /^プロジェクト行を表示/ })
  const todosSetting = settingsDialog.getByRole('checkbox', { name: /^タスクの下に Todo を表示/ })
  await displaySettings.click()
  await projectsSetting.check()
  await settingsDialog.getByRole('button', { name: '完了', exact: true }).click()
  const projectBar = page.locator('.vis-item.project-bar').filter({ hasText: '引越し準備' })
  await projectBar.waitFor()
  await page.getByRole('button', { name: '引越しを展開', exact: true }).click()
  const beforeTodo = await childBar.boundingBox()
  const summary = await projectBar.boundingBox()
  assert.ok(summary && beforeTodo)
  assert.ok(Math.abs(summary.x - beforeTodo.x) < 2 && Math.abs(summary.width - beforeTodo.width) < 2)
  await page.getByRole('button', { name: '引越し準備を折りたたむ', exact: true }).click()
  await childBar.waitFor({ state: 'hidden' })
  await page.getByRole('button', { name: '引越し準備を展開', exact: true }).click()
  await childBar.waitFor()

  await displaySettings.click()
  await todosSetting.check()
  await settingsDialog.getByRole('button', { name: '完了', exact: true }).click()
  const todoBar = page.locator('.vis-item.todo-bar').filter({ hasText: 'サイズを測る' })
  await todoBar.waitFor()
  const parentBar = page.locator('.vis-item.summary-bar').filter({ hasText: '引越し' })
  assert.equal(await projectBar.evaluate(el => getComputedStyle(el).borderTopStyle), 'double')
  assert.ok(await parentBar.evaluate(el => parseFloat(getComputedStyle(el, '::after').borderInlineStartWidth)) > 0)
  assert.ok(await todoBar.evaluate(el => parseFloat(getComputedStyle(el).borderTopLeftRadius)) > 100)
  assert.match(await todoBar.getAttribute('class'), /inherited-bar/)
  await todoBar.click()
  const todoDates = todoForm.getByRole('form', { name: 'Todo「サイズを測る」の日程' })
  assert.equal(await todoDates.getByLabel('開始日').inputValue(), chosen)
  await todoDates.getByLabel('開始日').fill(shift(chosen, 2))
  await todoDates.getByLabel('終了日').fill(shift(chosen, 3))
  await todoDates.getByRole('button', { name: '日程を保存' }).click()
  await page.locator('.vis-item.todo-bar:not(.inherited-bar)').filter({ hasText: 'サイズを測る' }).waitFor()
  const scheduledTodo = await todoBar.boundingBox()
  assert.ok(scheduledTodo)
  await drag(todoBar, scheduledTodo.width / 2)
  await todoBar.click()
  assert.equal(await todoDates.getByLabel('開始日').inputValue(), shift(chosen, 3))
  assert.equal(await todoDates.getByLabel('終了日').inputValue(), shift(chosen, 4))

  await page.reload()
  await projectBar.waitFor()
  await todoBar.click()
  assert.equal(await todoDates.getByLabel('開始日').inputValue(), shift(chosen, 3))
  await todoDates.getByRole('button', { name: 'タスクの日程に戻す' }).click()
  await page.locator('.vis-item.todo-bar.inherited-bar').filter({ hasText: 'サイズを測る' }).waitFor()
  await displaySettings.click()
  assert.equal(await projectsSetting.isChecked(), true)
  assert.equal(await todosSetting.isChecked(), true)
  await projectsSetting.uncheck()
  await settingsDialog.getByRole('button', { name: '完了', exact: true }).click()
  await projectBar.waitFor({ state: 'hidden' })
  await todoBar.waitFor()
  await displaySettings.click()
  await todosSetting.uncheck()
  await settingsDialog.getByRole('button', { name: '完了', exact: true }).click()
  await todoBar.waitFor({ state: 'hidden' })

  await sidebar.getByRole('button', { name: 'すべてのタスク' }).click()
  await page.getByRole('button', { name: '引越し 引越し準備' }).click()
  page.once('dialog', dialog => dialog.accept())
  await drawer.getByRole('button', { name: 'タスクを削除' }).click()
  await page.getByText('0 件のタスク').waitFor()
  assert.deepEqual(errors, [])
  console.log('ブラウザ検証成功: 既存ガントと疑問・懸念、プロジェクト行、Todo 行・日程編集、表示設定の復元')
} finally {
  await browser.close()
}
